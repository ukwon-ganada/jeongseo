"""이식이 어긋나지 않았는지 본다.

앱스 스크립트가 만들던 값과 한 글자라도 다르면 매번 「바뀜」으로 잡혀
온 시트가 헛되이 다시 써진다. 그래서 여기가 제일 중요하다.

    python3 test_hearing.py
"""
from hearing import make, kind, col_letter, find_col, flat, norm

COL = {"date": "next_date", "contents": "next_contents"}
fails = []


def eq(got, want, label):
    if got != want:
        fails.append("%s\n   나온 것 %r\n   바랄 것 %r" % (label, got, want))


def mk(date, contents):
    return make({"next_date": date, "next_contents": contents}, COL)


# ── hrMake_ ──────────────────────────────────────────────────────────
eq(mk("2026-08-26", "공판기일(413호법정 10:30)"),
   ("2026-08-26 공판기일", "2026-08-26 공판기일(413호법정 10:30)"),
   "보통 — 값은 종류까지, 메모는 통째로")

eq(mk("2026-08-26", "선고기일(301호법정 14:00)"),
   ("2026-08-26 선고기일", "2026-08-26 선고기일(301호법정 14:00)"),
   "선고기일")

eq(mk("2026-08-26", ""), ("2026-08-26", ""),
   "종류가 없으면 날짜만. 메모도 없음")

eq(mk("", "공판기일(413호법정)"), ("", ""),
   "날짜가 없으면 아무것도 — 그 칸은 건드리지 않는다")

eq(mk(None, "공판기일"), ("", ""), "날짜가 None")

eq(mk("2026-08-26T00:00:00+09:00", "공판기일"),
   ("2026-08-26 공판기일", "2026-08-26 공판기일"),
   "날짜 뒤에 시각이 붙어 와도 앞 열 글자만")

eq(mk("2026-08-26", "접수"), ("2026-08-26", "2026-08-26 접수"),
   "종류로 안 보이면 값에서 버리되 메모에는 남긴다")

eq(mk("2026-08-26", "  공판기일 ( 413호법정  10:30 ) "),
   ("2026-08-26 공판기일", "2026-08-26 공판기일 ( 413호법정 10:30 )"),
   "공백이 여럿이면 하나로")

eq(mk("26-08-26", "공판기일"), ("", ""), "연도가 두 자리면 날짜로 안 본다")

# ── hrKind_ ──────────────────────────────────────────────────────────
eq(kind("공판기일(413호법정 10:30)"), "공판기일", "괄호 앞까지")
eq(kind("심문기일(2회)"), "심문기일", "심문도 종류")
# 원본 규칙이 '심문'(審問)이지 '신문'(訊問)이 아니라서 '증인신문' 만으로는
# 종류로 안 잡힌다. 원본과 똑같이 두는 게 맞다 — 여기서 넓히면 시트에 이미
# 들어 있는 값과 어긋나 온 시트가 다시 써진다.
eq(kind("증인신문(2회)"), "", "'신문' 은 원본 규칙에 없다 — 원본 그대로")
eq(kind("증인신문기일(2회)"), "증인신문기일", "'기일' 이 붙으면 잡힌다")
eq(kind("변론종결"), "변론종결", "괄호가 없어도 그대로")
eq(kind("(413호법정)"), "", "괄호로 시작하면 없음")
eq(kind("서류접수"), "", "종류 낱말이 하나도 없으면 버린다")
eq(kind(""), "", "빈 것")
eq(kind(None), "", "None")

# ── hrFind_ — 정확일치를 먼저 본다 ────────────────────────────────────
eq(find_col(["1심사건번호", "사건번호", "성명"], "사건번호"), 2,
   "'1심사건번호' 가 먼저 있어도 딱 맞는 '사건번호' 를 고른다")
eq(find_col(["관할경찰서", "관할"], "관할"), 2,
   "'관할경찰서' 가 먼저 있어도 '관할' 을 고른다 — 예전에 사고 났던 자리")
eq(find_col(["관할경찰서"], "관할"), 1,
   "딱 맞는 게 없으면 앞글자가 같은 것")
eq(find_col(["성 명", "기 일"], "기일"), 2, "머리글 안의 공백은 무시")
eq(find_col(["성명"], "기일"), 0, "없으면 0")

# ── hrL_ ─────────────────────────────────────────────────────────────
eq(col_letter(1), "A", "1 → A")
eq(col_letter(26), "Z", "26 → Z")
eq(col_letter(27), "AA", "27 → AA")
eq(col_letter(52), "AZ", "52 → AZ")
eq(col_letter(53), "BA", "53 → BA")

# ── 쳇바퀴 검사 — 두 번째 실행이 0건이어야 한다 ────────────────────────
rec = {"next_date": "2026-08-26", "next_contents": "공판기일(413호법정 10:30)"}
t1, n1 = make(rec, COL)
eq(flat(t1), t1, "만든 값을 다시 flat 해도 그대로여야 한다 (안 그러면 영영 다시 씀)")
eq(norm("2026고단101290 "), "2026고단101290", "사건번호 견주기는 공백을 지우고")

# ── 결과 ─────────────────────────────────────────────────────────────
if fails:
    print("실패 %d건\n" % len(fails))
    for f in fails:
        print(" ✗ " + f + "\n")
    raise SystemExit(1)
print("통과")
